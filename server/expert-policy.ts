import {z} from 'zod';

export const handlingSchema=z.object({
 mode:z.enum(['quiet','direct','deep']),
 trigger:z.enum(['none','explicit','conflict','tradeoff','coupled_rules']),
 reason:z.string().trim().max(240),
}).strict().superRefine((value,ctx)=>{
 if(value.mode==='deep'&&(value.trigger==='none'||!value.reason))ctx.addIssue({code:'custom',message:'深入评估必须说明具体触发原因'});
 if(value.mode!=='deep'&&value.trigger!=='none')ctx.addIssue({code:'custom',message:'普通回应不标记深入评估原因'});
});

